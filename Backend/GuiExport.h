#ifndef GUIEXPORT_H
#define GUIEXPORT_H

#include <fstream>
#include "Case.h"
#include "Interrogation.h"

// Makes a piece of text safe to put inside "quotes" in a JavaScript file.
inline string jsText(const string& s) {
    string out = "";
    for (size_t i = 0; i < s.size(); i++) {
        char ch = s[i];
        if (ch == '\\') out += "\\\\";
        else if (ch == '"') out += "\\\"";
        else if (ch == '\n') out += "\\n";
        else if (ch == '\r') out += "";
        else out += ch;
    }
    return out;
}

// Writes one suspect (details + all questions and answers) for the GUI.
inline void writeSuspect(ofstream& f, Case& c, int id, Interrogation& talk) {
    Suspect* s = c.findSuspect(id);
    f << "    {id:" << id
      << ", name:\"" << jsText(s->getName()) << "\""
      << ", role:\"" << jsText(s->getOccupation()) << "\""
      << ", age:" << s->getAge()
      << ", bio:\"" << jsText(s->getBackground()) << "\""
      << ", questions:[\n";
    for (int q = 1; q <= talk.getQuestionCount(); q++) {
        f << "      [\"" << jsText(talk.getQuestion(q)) << "\", \""
          << jsText(talk.getAnswer(q)) << "\"]";
        if (q < talk.getQuestionCount()) f << ",";
        f << "\n";
    }
    f << "    ]}";
}

// Creates case_data.js so the GUI shows exactly what the C++ Case contains.
inline void exportForGui(Case& c, Interrogation& victor, Interrogation& adrian,
                         Interrogation& nina, Interrogation& felix, int culpritId) {
    ofstream f("case_data.js");
    if (!f) { cout << "\nCould not create case_data.js" << endl; return; }

    f << "// AUTO-GENERATED by the C++ backend (GuiExport.h). Do not edit by hand.\n";
    f << "window.BACKEND = {\n";
    f << "  culpritId: " << culpritId << ",\n";

    f << "  suspects: [\n";
    writeSuspect(f, c, 1, victor);  f << ",\n";
    writeSuspect(f, c, 2, adrian);  f << ",\n";
    writeSuspect(f, c, 3, nina);    f << ",\n";
    writeSuspect(f, c, 4, felix);   f << "\n";
    f << "  ],\n";

    f << "  clues: [\n";
    for (int id = 1; id <= c.getClueCount(); id++) {
        Clue* k = c.findClue(id);
        f << "    {id:" << id
          << ", title:\"" << jsText(k->getTitle()) << "\""
          << ", desc:\"" << jsText(k->getDescription()) << "\""
          << ", pointsTo:" << k->getPointsTo() << "}";
        if (id < c.getClueCount()) f << ",";
        f << "\n";
    }
    f << "  ]\n";
    f << "};\n";
    f.close();
    cout << "\n[GUI export] case_data.js written. Copy it into the GUI folder." << endl;
}

#endif
